#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Embed the A830 board glue and the pinned gen80000 firmware into build/adreno830/libAdreno830.a.

Runs after component:Adreno830 in [kernel] archives. It generates PianoGpuFirmwarePins.h (the SHA-256
pins the driver checks at S0), compiles the board glue of drivers/Adreno830/board, turns the pinned
images in <device>/scripts/data/piano-gpu-inputs.json into one page-aligned object, and appends all of
it to the A830 archive. Linux toolchain: the same llvm the rest of the archive build uses.

The pins were taken from this phone (Xiaomi Pad 8 Pro, HyperOS): the three gen80000 images are byte
for byte the ones the OnePlus 13T port pins, and piano has no Gen8 ZAP image, so the ZAP entry stays
zero length and the driver's own zero-length default applies.
"""
import argparse
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEVICE = Path(os.environ.get('UNIXNU_DEVICE', ''))
RECORD = ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json'
ARCHIVE = ROOT / 'build/adreno830/libAdreno830.a'
OUT = ROOT / 'build/piano-gpu'
PINS = DEVICE / 'scripts/data/piano-gpu-inputs.json'
BOARD = ROOT / 'drivers/Adreno830/board'
WARNINGS = ['-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter', '-Wno-c99-designator', '-Wno-reorder-init-list',
            '-Wno-deprecated-enum-enum-conversion', '-Wno-unnecessary-virtual-specifier', '-Wno-sign-conversion',
            '-Wno-shorten-64-to-32']
HEADER_NAMES = {'native_adreno_firmware_image': 'GMU', 'native_adreno_sqe_firmware_image': 'SQE',
                'native_adreno_aqe_firmware_image': 'AQE', 'native_adreno_zap_image': 'ZAP'}


def fail(message):
    raise SystemExit('build-piano-gpu: ' + message)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def command(record, source, obj, extra):
    arguments, result, i = record['arguments'], [], 0
    while i < len(arguments):
        value = arguments[i]
        if value == record['file']:
            result.append(str(source))
        elif value == '-o':
            result += ['-o', str(obj)]
            i += 1
        elif value in ('-MF', '-MJ', '-MT', '-MQ'):
            i += 1
        elif value == '-Xclang' and i + 1 < len(arguments) and arguments[i + 1].startswith('-W'):
            i += 1
        elif not value.startswith('-W') and value not in ('-MD', '-MP', '-MMD'):
            result.append(value)
        i += 1
    return result + extra


def compile_one(record, source, obj, extra):
    obj.parent.mkdir(parents=True, exist_ok=True)
    obj.unlink(missing_ok=True)
    result = subprocess.run(command(record, source, obj, extra), cwd=record['directory'],
                            capture_output=True, text=True)
    output = (result.stdout + result.stderr).strip()
    if result.returncode:
        fail(f'{source}:\n{output[-4000:]}')
    if 'warning:' in output:
        fail(f'{source} compiled with warnings:\n{output[-4000:]}')
    magic, cpu, _, kind = struct.unpack_from('<4I', obj.read_bytes())
    if (magic, cpu, kind) != (0xfeedfacf, 0x100000c, 1):
        fail(f'{obj}: not an ARM64 Mach-O object')
    return obj


def pins_header(pins):
    header = ['// Generated by scripts/build-piano-gpu.py from scripts/data/piano-gpu-inputs.json.',
              '#pragma once', '#include <stdint.h>']
    for symbol, label in HEADER_NAMES.items():
        entry = next((item for item in pins['files'].values() if item['symbol'] == symbol), None)
        digest = bytes.fromhex(entry['sha256']) if entry else bytes(32)
        mac = f'PIANO_GPU_FW_{label}_SHA256'
        note = f'{entry and "pinned" or "no Gen8 ZAP on this board: zero pin"}'
        header.append(f'inline constexpr uint8_t {mac}[32]={{' + ','.join(f'{b:#04x}' for b in digest) + f'}};  // {note}')
    return '\n'.join(header) + '\n'


def firmware_assembly(pins, directory):
    lines = ['// Generated by scripts/build-piano-gpu.py: the pinned gen80000 images, page aligned.',
             '.section __DATA_CONST,__const']
    for name, entry in pins['files'].items():
        if not entry['bytes']:
            continue                     # the driver's own zero-length default provides it
        path = directory / name
        data = path.read_bytes() if path.is_file() else b''
        if len(data) != entry['bytes'] or sha(data) != entry['sha256']:
            fail(f'{path} is missing or does not match its pin ({entry["bytes"]} bytes, {entry["sha256"]})')
        label = '_' + entry['symbol']
        lines += ['.p2align 12', f'.globl {label}', f'{label}:',
                  f'.incbin {json.dumps(str(path.resolve()))}', f'{label}_end:', '.p2align 3',
                  f'.globl {label}_size', f'{label}_size:', f'.quad {label}_end-{label}']
    return '\n'.join(lines) + '\n'


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--no-firmware', action='store_true', help='link the board glue without the images')
    options = args.parse_args()
    if not ARCHIVE.is_file():
        fail(f'{ARCHIVE} missing; list "component:Adreno830" before this script in [kernel] archives')
    if not RECORD.is_file():
        fail(f'{RECORD} missing; run the XNU bootstrap pass first')
    if not PINS.is_file():
        fail(f'{PINS} missing')
    record = json.loads(RECORD.read_text().strip().rstrip(','))
    pins = json.loads(PINS.read_text())
    # The images live beside the component; the tree's drivers/Adreno830 is a link to it, so resolve
    # the recorded directory against the tree rather than the device repository root.
    directory = ROOT / pins['directory']
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'PianoGpuFirmwarePins.h').write_text(pins_header(pins))

    extra = ['-I', str(BOARD), '-I', str(ROOT / 'drivers/Adreno830'), '-I', str(ROOT / 'drivers/Adreno830/platform/sm8750'),
             '-I', str(ROOT / 'kits/Sm8750Platform'), '-I', str(OUT), '-I', str(ROOT / '.cache/xnu-work/osfmk'), *WARNINGS]
    objects = [compile_one(record, BOARD / 'PianoGpuBoard.cpp', OUT / 'PianoGpuBoard.o', extra)]
    if (BOARD / 'PianoGpuTrace.cpp').is_file():
        objects.append(compile_one(record, BOARD / 'PianoGpuTrace.cpp', OUT / 'PianoGpuTrace.o', extra))
    if not options.no_firmware:
        source = OUT / 'firmware.S'
        source.write_text(firmware_assembly(pins, directory))
        firmware = OUT / 'firmware.o'
        firmware.unlink(missing_ok=True)
        run = subprocess.run([shutil.which('clang') or 'clang', '-target', 'arm64-apple-ios17.0',
                              '-Wno-incompatible-sysroot', '-c', str(source), '-o', str(firmware)],
                             capture_output=True, text=True)
        if run.returncode:
            fail(f'firmware assembly:\n{(run.stdout + run.stderr)[-3000:]}')
        objects.append(firmware)
    subprocess.run([shutil.which('llvm-ar') or 'llvm-ar', 'rcs', str(ARCHIVE), *map(str, objects)], check=True)
    print(f'build-piano-gpu: board glue and {len(objects) - 2} firmware image(s) added to {ARCHIVE}')


if __name__ == '__main__':
    main()
